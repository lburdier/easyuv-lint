pub fn t(lang: Lang, key: &str) -> &'static str {
    STRINGS.iter().find(|s| s.0 == key).map(|s| if lang == Lang::Fr { s.2 } else { s.1 }).unwrap_or("?")
}

/// Singular or plural form of a counted noun ("1 file", "2 files").
pub fn count(lang: Lang, n: usize, key: &str) -> String {
    let word = if n == 1 { t(lang, &format!("{key}.1")) } else { t(lang, key) };
    format!("{n} {word}")
}

