#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn numbers_follow_the_language() {
        assert_eq!(num(Lang::En, 12345.678, 1), "12,345.7");
        assert_eq!(num(Lang::Fr, 12345.678, 1), "12\u{202f}345,7");
        assert_eq!(num(Lang::En, 0.0, 0), "0");
        assert_eq!(num(Lang::En, -3.0, 0), "-3");
    }
}
