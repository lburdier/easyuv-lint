//! English and French interface strings and number formatting.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    En,
    Fr,
}

impl Lang {
    pub fn parse(s: &str) -> Option<Lang> {
        let s = s.to_ascii_lowercase();
        if s.starts_with("fr") {
            Some(Lang::Fr)
        } else if s.starts_with("en") {
            Some(Lang::En)
        } else {
            None
        }
    }

    /// From EASYUV_LINT_LANG, then LANG / LC_ALL; English by default.
    pub fn from_env() -> Lang {
        ["EASYUV_LINT_LANG", "LC_ALL", "LANG"].iter().find_map(|k| std::env::var(k).ok().and_then(|v| Lang::parse(&v))).unwrap_or(Lang::En)
    }

    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Fr => "fr",
        }
    }
}

/// Number with grouped thousands: 12,345.6 in English, 12 345,6 in French.
pub fn num(lang: Lang, v: f64, decimals: usize) -> String {
    if !v.is_finite() {
        return "∞".into();
    }
    let s = format!("{:.*}", decimals, v.abs());
    let (int, frac) = s.split_once('.').map(|(a, b)| (a.to_string(), Some(b.to_string()))).unwrap_or((s.clone(), None));
    let (sep, dot) = match lang {
        Lang::En => (",", "."),
        Lang::Fr => ("\u{202f}", ","),
    };
    let mut grouped = String::new();
    for (i, c) in int.chars().enumerate() {
        if i > 0 && (int.len() - i) % 3 == 0 {
            grouped.push_str(sep);
        }
        grouped.push(c);
    }
    let sign = if v < 0.0 && v.abs() >= 0.5 * 10f64.powi(-(decimals as i32)) { "-" } else { "" };
    match frac {
        Some(f) => format!("{sign}{grouped}{dot}{f}"),
        None => format!("{sign}{grouped}"),
    }
}

